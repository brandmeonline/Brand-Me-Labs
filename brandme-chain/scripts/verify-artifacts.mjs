#!/usr/bin/env node
// Hash every compiled contract artifact and compare against (or write) the
// committed manifest. A contract compiled with one tuple must never be served
// with another tuple's proving material: the adapter refuses to load a
// contract whose artifacts do not match this manifest.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const toolchain = JSON.parse(readFileSync(join(root, 'contracts/toolchain.json'), 'utf8'));
const manifestPath = join(root, 'contracts/artifact-manifest.json');
const write = process.argv.includes('--write');

const sha256 = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');
const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

function compilerVersion() {
  const bin = join(process.env.COMPACT_HOME ?? join(root, '.compact', toolchain.compactc.version), 'compactc');
  if (!existsSync(bin)) return null;
  return execFileSync(bin, ['--version']).toString().trim();
}

function build() {
  const contracts = {};
  for (const f of readdirSync(join(root, 'contracts/src')).filter((n) => n.endsWith('.compact')).sort()) {
    const name = f.replace(/\.compact$/, '');
    const out = join(root, 'contracts/managed', name);
    if (!existsSync(out)) throw new Error(`missing compiled output for ${name}; run pnpm compact:compile`);
    const files = {};
    for (const p of walk(out).sort()) {
      if (p.endsWith('.js.map')) continue;
      files[relative(out, p)] = sha256(p);
    }
    contracts[name] = { source: { path: `contracts/src/${f}`, sha256: sha256(join(root, 'contracts/src', f)) }, files };
  }
  return {
    schema: 'brandme.midnight.artifact-manifest/v1',
    compactc: toolchain.compactc.version,
    languageVersion: toolchain.compactc.languageVersion,
    runtimeVersion: toolchain.compactc.runtimeVersion,
    contracts,
  };
}

const actual = build();
if (write) {
  const v = compilerVersion();
  if (v !== toolchain.compactc.version) throw new Error(`compactc ${v} != pinned ${toolchain.compactc.version}`);
  writeFileSync(manifestPath, JSON.stringify(actual, null, 2) + '\n');
  console.log(`wrote ${relative(root, manifestPath)}`);
  process.exit(0);
}

const expected = JSON.parse(readFileSync(manifestPath, 'utf8'));
const problems = [];
for (const [name, c] of Object.entries(expected.contracts)) {
  const a = actual.contracts[name];
  if (!a) { problems.push(`${name}: not compiled`); continue; }
  if (a.source.sha256 !== c.source.sha256) problems.push(`${name}: source changed since manifest`);
  for (const [file, h] of Object.entries(c.files)) {
    if (a.files[file] === undefined) {
      // Prover keys are not committed (≈5 MB each); they are regenerated by compile.
      if (file.endsWith('.prover')) continue;
      problems.push(`${name}/${file}: missing`);
    } else if (a.files[file] !== h) problems.push(`${name}/${file}: hash mismatch`);
  }
}
if (problems.length) {
  console.error('artifact manifest verification FAILED:\n  ' + problems.join('\n  '));
  process.exit(1);
}
console.log(`artifact manifest OK (compactc ${expected.compactc}, ${Object.keys(expected.contracts).length} contract(s))`);
