// Development-only ES256 key pair for the gateway -> consumer-domain principal
// assertion (brandme-gateway/src/services/domains.ts signs; the service verifies
// with brandme_core/domains/persona/assertion.py). Generated at runtime OUTSIDE the
// repository by default, so neither the compose bind mount (./:/app) nor a docker
// build context ever contains the private key. Never commit them; never use them
// outside demo/development (sandbox/production keys live in Secret Manager,
// docs/build/security/credential-manifest.yaml CONSUMER_DOMAIN_ASSERTION_KEY).
//
//   node scripts/dev/consumer-domain-keys.mjs             # create once; keeps an existing pair
//   node scripts/dev/consumer-domain-keys.mjs --rotate    # replace the pair (restart both services)
//   node scripts/dev/consumer-domain-keys.mjs --out DIR   # default: $BRANDME_DEV_KEYS_DIR, else ~/.config/brandme/dev-keys
//   (docker-compose.yml reads the same default; set BRANDME_DEV_KEYS_DIR for both or neither)
//
// Writes (directory 0700, files 0600):
//   consumer-domains-gateway.env  CONSUMER_DOMAIN_ASSERTION_KID and CONSUMER_DOMAIN_ASSERTION_KEY
//                                 (PKCS#8 PEM): the gateway's env_file
//   consumer-domains-service.env  CONSUMER_DOMAIN_ASSERTION_JWKS (public key only): the
//                                 consumer-domains service's env_file
// Prints the kid and the paths only, never key material. Inside the repository it
// refuses an output directory that git does not ignore.
//
// Node built-ins only.
import { spawnSync } from 'node:child_process';
import { createPrivateKey, createPublicKey, generateKeyPairSync, randomBytes, sign, verify } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
// Same default as docker-compose.yml's env_file paths.
export const DEFAULT_DIR = process.env.BRANDME_DEV_KEYS_DIR || join(homedir(), '.config', 'brandme', 'dev-keys');
export const GATEWAY_FILE = 'consumer-domains-gateway.env';
export const SERVICE_FILE = 'consumer-domains-service.env';
const HEADER = '# Generated by scripts/dev/consumer-domain-keys.mjs for demo/development only. Never commit.\n';

/** A fresh P-256 pair: the gateway's PKCS#8 PEM and kid, and the service's public JWKS. */
export function generatePair(now = new Date()) {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  // Same alphabet the gateway accepts for a kid (brandme-gateway/src/config/index.ts:128).
  const kid = `dev-${now.toISOString().slice(0, 10)}-${randomBytes(4).toString('hex')}`;
  const pem = privateKey.export({ type: 'pkcs8', format: 'pem' });
  const { kty, crv, x, y } = publicKey.export({ format: 'jwk' });
  return { kid, pem, jwks: { keys: [{ kty, crv, kid, x, y, use: 'sig', alg: 'ES256' }] } };
}

/** Compose env_file text: a double-quoted value expands \n, a single-quoted one is literal. */
export function envFiles({ kid, pem, jwks }) {
  return {
    gateway: `${HEADER}CONSUMER_DOMAIN_ASSERTION_KID=${kid}\n`
      + `CONSUMER_DOMAIN_ASSERTION_KEY="${pem.trim().split('\n').join('\\n')}\\n"\n`,
    service: `${HEADER}# Public key only.\nCONSUMER_DOMAIN_ASSERTION_JWKS='${JSON.stringify(jwks)}'\n`,
  };
}

/** Read both files back the way compose does and check they hold one matching pair. */
export function readPair(dir) {
  const values = {};
  for (const file of [GATEWAY_FILE, SERVICE_FILE]) {
    for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
      const m = /^([A-Z_]+)=(?:"(.*)"|'(.*)'|(.*))$/.exec(line);
      if (m) values[m[1]] = m[2] !== undefined ? m[2].replace(/\\n/g, '\n') : (m[3] ?? m[4]);
    }
  }
  const kid = values.CONSUMER_DOMAIN_ASSERTION_KID;
  const jwks = JSON.parse(values.CONSUMER_DOMAIN_ASSERTION_JWKS ?? '{}');
  const jwk = (jwks.keys ?? []).find((k) => k.kid === kid);
  if (!kid || !jwk || 'd' in jwk || !values.CONSUMER_DOMAIN_ASSERTION_KEY) throw new Error('key files do not hold one matching pair');
  const message = randomBytes(32);
  const signature = sign('sha256', message, createPrivateKey(values.CONSUMER_DOMAIN_ASSERTION_KEY));
  if (!verify('sha256', message, createPublicKey({ key: jwk, format: 'jwk' }), signature)) {
    throw new Error('the private key does not match the published public key');
  }
  return { kid };
}

function writePrivate(path, text) {
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, text, { mode: 0o600 });
  chmodSync(tmp, 0o600);
  renameSync(tmp, path);
}

function assertIgnored(dir) {
  const rel = relative(ROOT, dir);
  if (rel.startsWith('..') || isAbsolute(rel)) return; // outside the repository
  const probe = join(rel, GATEWAY_FILE);
  const r = spawnSync('git', ['check-ignore', '-q', '--no-index', probe], { cwd: ROOT });
  if (r.status !== 0) throw new Error(`${probe} is not gitignored; refusing to write key material there`);
}

export function main(argv) {
  const at = argv.indexOf('--out');
  const dir = resolve(at >= 0 ? argv[at + 1] ?? '' : DEFAULT_DIR);
  const rotate = argv.includes('--rotate');
  const unknown = argv.filter((a, i) => !['--out', '--rotate'].includes(a) && !(at >= 0 && i === at + 1));
  if (unknown.length || (at >= 0 && !argv[at + 1])) {
    console.error('usage: node scripts/dev/consumer-domain-keys.mjs [--rotate] [--out DIR]');
    return 64;
  }
  assertIgnored(dir);
  const both = existsSync(join(dir, GATEWAY_FILE)) && existsSync(join(dir, SERVICE_FILE));
  if (both && !rotate) {
    const { kid } = readPair(dir);
    console.log(`consumer-domain dev key pair kept (kid ${kid}) in ${dir}; --rotate replaces it`);
    return 0;
  }
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  chmodSync(dir, 0o700);
  const pair = generatePair();
  const files = envFiles(pair);
  writePrivate(join(dir, GATEWAY_FILE), files.gateway);
  writePrivate(join(dir, SERVICE_FILE), files.service);
  readPair(dir);
  console.log(`consumer-domain dev key pair written (kid ${pair.kid}):\n  ${join(dir, GATEWAY_FILE)} (gateway: private key)\n`
    + `  ${join(dir, SERVICE_FILE)} (consumer-domains: public JWKS)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (e) {
    console.error(`consumer-domain-keys: ${e.message}`);
    process.exit(1);
  }
}
